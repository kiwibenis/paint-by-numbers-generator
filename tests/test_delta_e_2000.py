def test_matches_ciede2000_reference_data(
    first: Lab,
    second: Lab,
    expected: float,
) -> None:
    delta = DeltaE2000()

    assert delta.distance(
        first,
        second,
    ) == pytest.approx(
        expected,
        abs=0.0001,
    )


def test_identical_colors_have_zero_distance() -> None:
    delta = DeltaE2000()

    color = Lab(
        l=50.0,
        a=20.0,
        b=-10.0,
    )

    assert delta.distance(
        color,
        color,
    ) == pytest.approx(0.0)


def test_distance_is_symmetric() -> None:
    delta = DeltaE2000()

    first = Lab(
        l=40.0,
        a=10.0,
        b=-20.0,
    )

    second = Lab(
        l=70.0,
        a=-5.0,
        b=15.0,
    )

    assert delta.distance(
        first,
        second,
    ) == pytest.approx(
        delta.distance(
            second,
            first,
        ),
    )


def test_distance_is_positive() -> None:
    delta = DeltaE2000()

    first = Lab(
        l=20.0,
        a=5.0,
        b=5.0,
    )

    second = Lab(
        l=80.0,
        a=-10.0,
        b=15.0,
    )

    assert (
        delta.distance(
            first,
            second,
        )
        > 0.0
    )
